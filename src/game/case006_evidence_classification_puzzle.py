class Case006EvidenceClassificationPuzzle:

    def __init__(self, puzzle_data):
        self.puzzle_data = puzzle_data
        self.unlocks = puzzle_data.get("unlocks", [])

        self.required_analysis = {
            "identification_left_in_vehicle_identified": True,
            "planned_disappearance_contradiction_identified": True,
            "silent_call_identified": True,
            "silent_call_low_reliability_identified": True,
            "caller_identity_unproven": True
        }

    def check_answer(self, answer):
        if not isinstance(answer, dict):
            return False

        for key, expected_value in self.required_analysis.items():
            actual_value = answer.get(key)

            if not isinstance(actual_value, bool):
                return False

            if actual_value != expected_value:
                return False

        return True

    def get_unlocked_evidence(self):
        return self.unlocks